import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import { initializeApp, deleteApp } from 'firebase/app';
import { connectAuthEmulator, getAuth, signInWithEmailAndPassword, signOut } from 'firebase/auth';
import { connectFirestoreEmulator, doc, getDoc, getDocs, collection, getFirestore, setDoc, Timestamp, terminate } from 'firebase/firestore';

if (!process.env.FIREBASE_AUTH_EMULATOR_HOST || !process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Yalnız demo emülatörleriyle çalıştırılır.');
Object.assign(process.env,{VITE_FIREBASE_API_KEY:'demo-key',VITE_FIREBASE_AUTH_DOMAIN:'demo-ieee-hub.firebaseapp.com',VITE_FIREBASE_PROJECT_ID:'demo-ieee-hub',VITE_FIREBASE_APP_ID:'demo-app',VITE_USE_EMULATORS:'1',VITE_AUTH_EMULATOR_PORT:'9099',VITE_FIRESTORE_EMULATOR_PORT:'8085'});
const app=initializeApp({apiKey:'demo-key',projectId:'demo-ieee-hub'});
const auth=getAuth(app);connectAuthEmulator(auth,'http://127.0.0.1:9099',{disableWarnings:true});
const db=getFirestore(app);connectFirestoreEmulator(db,'127.0.0.1',8085);
const out=fileURLToPath(new URL('../smoke-shots/statutory-setup/',import.meta.url));
await mkdir(out,{recursive:true});
const server=await createServer({root:fileURLToPath(new URL('..',import.meta.url)),logLevel:'warn',server:{host:'127.0.0.1',port:5186,strictPort:true}});
let browser;
try {
  const user=(await signInWithEmailAndPassword(auth,'baskan@demo.ieee','demo1234')).user;
  await setDoc(doc(db,'roles','review-advisor'),{name:'Akademik Danışman',scope:'branch',permissions:['governance.read'],active:true,order:99});
  const existing=(await getDocs(collection(db,'assignments'))).docs[0].data();
  await setDoc(doc(db,'assignments','review-advisor'),{...existing,uid:user.uid,memberName:'Görevli Danışman',roleId:'review-advisor',roleName:'Akademik Danışman',unitId:'branch',unitName:'Kol geneli',status:'active',startsAt:Timestamp.fromMillis(Date.now()-3600000),endsAt:Timestamp.fromMillis(Date.now()+86400000)});
  const boardsBefore=(await getDoc(doc(db,'settings','boards'))).data();
  await server.listen();
  browser=await chromium.launch({executablePath:process.env.BROWSER_PATH??'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
  const page=await browser.newPage({viewport:{width:1366,height:950},locale:'tr-TR'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('http://127.0.0.1:5186');
  await page.getByText('Ayşe Yılmaz',{exact:true}).click();
  await page.getByRole('button',{name:'Kullanıcı menüsü'}).waitFor();
  await page.goto('http://127.0.0.1:5186/surecler');
  const review=page.getByRole('button',{name:'Eşlemeleri gözden geçir ve yayımla',exact:true});
  await review.waitFor();
  assert.equal(await review.isEnabled(),false,'Eksik rol varken yayımlama açılmamalı.');
  await page.getByRole('button',{name:'Eksik tüzük rollerini ekle',exact:true}).click();
  await page.getByText(/eksik rol eklendi/).waitFor();
  assert.equal((await getDoc(doc(db,'roles','akademik-danisman'))).exists(),false,'Aynı adlı danışman rolü tekrar oluşturulmamalı.');
  const advisor=page.getByTestId('statutory-role-advisor');
  await advisor.getByRole('combobox').click();
  await page.getByRole('option',{name:/branch__review-advisor/}).click();
  await advisor.getByText('Aktif görevliler: Görevli Danışman',{exact:true}).waitFor();
  const holidays=page.getByLabel('Resmî tatiller (YYYY-MM-DD; her satıra bir tarih)',{exact:true});
  await holidays.fill('2027-02-30');
  assert.equal(await review.isEnabled(),false,'Geçersiz takvim tarihi reddedilmeli.');
  await holidays.fill('2027-01-01');await holidays.press('Enter');
  assert.equal(await holidays.inputValue(),'2027-01-01\n','Yeni tarih için satır sonu korunmalı.');
  await holidays.pressSequentially('2027-04-23');
  await review.waitFor({state:'visible'});
  assert.equal(await review.isEnabled(),true,`Geçerli eşlemelerle gözden geçirme açılmalı: ${await page.getByTestId('statutory-setup').locator('[data-testid^="statutory-role-"]').filter({hasText:'Aktif bir rol ve uygun birim seçin.'}).allTextContents()}; takvim: ${await holidays.inputValue()}`);
  await page.getByTestId('statutory-setup').screenshot({path:out+'desktop.png',animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Mobilde yatay taşma olmamalı.');
  await page.getByTestId('statutory-setup').screenshot({path:out+'mobile.png',animations:'disabled'});
  await review.click();
  const modal=page.getByRole('dialog');await modal.getByText('Tüzük kurulumunu son kez kontrol et',{exact:true}).waitFor();
  await modal.getByText('Görevli Danışman',{exact:true}).waitFor();
  assert.equal((await getDoc(doc(db,'settings','statutory'))).exists(),false,'Son inceleme öncesi politika yayımlanmamalı.');
  await modal.getByRole('button',{name:'Tüzük süreç politikasını yayımla',exact:true}).click();
  await page.getByText('Yeni politika sürümü yayımlandı; açık dosyalar önceki sürümde kalır.',{exact:true}).waitFor();
  const pointer=(await getDoc(doc(db,'settings','statutory'))).data();
  const policy=(await getDoc(doc(db,'statutoryPolicies',pointer.policyId))).data();
  assert.equal(policy.roles.advisor,'branch__review-advisor');
  assert.deepEqual(policy.holidays,['2027-01-01','2027-04-23']);
  assert.deepEqual((await getDoc(doc(db,'settings','boards'))).data(),boardsBefore,'Kurul ayarları değişmemeli.');
  await page.goto('http://127.0.0.1:5186/yonetim/roller');
  await page.getByText('Rol kimliği: review-advisor',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Tüzük kurulumu: aynı adlı rol ayrımı, görevli gösterimi, geçersiz eşleme/tarih, mobil görünüm, son inceleme ve doğru politika kaydı geçti. Kurul ayarları korunuyor.');
} finally {await browser?.close();await server.close();await signOut(auth);await terminate(db);await deleteApp(app);}
