import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import { initializeApp, deleteApp } from 'firebase/app';
import { connectAuthEmulator, getAuth, signInWithEmailAndPassword, signOut } from 'firebase/auth';
import { collection, connectFirestoreEmulator, deleteDoc, doc, getDoc, getDocs, getFirestore, setDoc, terminate, updateDoc } from 'firebase/firestore';

if (!process.env.FIREBASE_AUTH_EMULATOR_HOST || !process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Yalnız demo emülatörleriyle çalıştırılır.');
Object.assign(process.env, { VITE_FIREBASE_API_KEY: 'demo-key', VITE_FIREBASE_AUTH_DOMAIN: 'demo-ieee-hub.firebaseapp.com', VITE_FIREBASE_PROJECT_ID: 'demo-ieee-hub', VITE_FIREBASE_APP_ID: 'demo-app', VITE_USE_EMULATORS: '1', VITE_AUTH_EMULATOR_PORT: '9099', VITE_FIRESTORE_EMULATOR_PORT: '8085' });
const app = initializeApp({ apiKey: 'demo-key', projectId: 'demo-ieee-hub' });
const auth = getAuth(app);
connectAuthEmulator(auth, 'http://127.0.0.1:9099', { disableWarnings: true });
const db = getFirestore(app);
connectFirestoreEmulator(db, '127.0.0.1', 8085);
const out = fileURLToPath(new URL('../smoke-shots/usability/', import.meta.url));
await mkdir(out, { recursive: true });
const server = await createServer({ root: fileURLToPath(new URL('..', import.meta.url)), logLevel: 'warn', server: { host: '127.0.0.1', port: 5187, strictPort: true } });
const base = 'http://127.0.0.1:5187';
let browser;
let lastPage;
let memberRef;
let memberBefore;
const errors = [];
try {
  await signInWithEmailAndPassword(auth, 'baskan@demo.ieee', 'demo1234');
  const members = await getDocs(collection(db, 'members'));
  const recipient = members.docs.find((item) => item.data().email === 'yeni@demo.ieee');
  assert.ok(recipient);
  memberRef = recipient.ref;
  memberBefore = recipient.data();
  await updateDoc(memberRef, { status: 'active' });
  const role = (await getDoc(doc(db, 'roles', 'birim-baskani'))).data();
  await setDoc(doc(db, 'roles', 'smoke-duplicate'), { ...role, order: 99 });
  await server.listen();
  browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const login = async (name) => {
    const context = await browser.newContext({ viewport: { width: 1366, height: 950 }, locale: 'tr-TR' });
    const page = await context.newPage();
    lastPage = page;
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
    await page.goto(base);
    await page.getByText(name, { exact: true }).click();
    await page.getByRole('button', { name: 'Kullanıcı menüsü' }).waitFor();
    return page;
  };
  const admin = await login('Ayşe Yılmaz');
  await admin.getByRole('heading', { name: /Merhaba Ayşe/ }).waitFor();
  await admin.getByRole('link', { name: 'Komite çalışma alanı', exact: true }).waitFor();
  const nav = admin.locator('.mantine-AppShell-navbar');
  assert.equal(await nav.getByRole('link', { name: 'Üyeler', exact: true }).isVisible(), false);
  await admin.screenshot({ path: out + 'dashboard-desktop.png', fullPage: true });
  await admin.keyboard.press('Control+k');
  await admin.getByRole('textbox', { name: 'İşlem ara' }).fill('roller yetkiler');
  await admin.getByRole('dialog').getByRole('link', { name: 'Roller ve yetkiler' }).click();
  await admin.waitForURL('**/yonetim/roller');
  await admin.getByRole('textbox', { name: 'Rol ara' }).fill('Başkan');
  await admin.getByLabel(/Aynı adlı kayıtlar/).check();
  await admin.getByText('Rol kimliği: smoke-duplicate', { exact: true }).waitFor();
  await admin.getByText('Rol kimliği: birim-baskani', { exact: true }).waitFor();
  await admin.screenshot({ path: out + 'roles-desktop.png', fullPage: true });
  console.log('Menü araması ve aynı adlı rol karşılaştırması geçti.');
  await admin.goto(base + '/birimler/cs');
  await admin.getByRole('heading', { name: 'Computer Society', exact: true }).waitFor();
  await admin.getByRole('link', { name: /Başvuru yönetimi.*Komitenin ilanları/ }).click();
  await admin.waitForURL('**/basvuru-yonetimi?birim=cs');
  assert.match(await admin.getByRole('combobox', { name: 'Yönettiğiniz birim' }).inputValue(), /Computer Society|^cs$/);

  await admin.goto(base + '/yonetim/sablonlar');
  await admin.getByRole('button', { name: 'Kişisel imza şablonu', exact: true }).click();
  await admin.getByRole('dialog').getByLabel('Şablon adı').fill('Tarayıcı kişisel imza');
  await admin.getByRole('button', { name: 'Oluştur ve düzenle' }).click();
  await admin.waitForURL('**/yonetim/sablonlar/tarayici-kisisel-imza');
  await admin.getByRole('button', { name: 'Yayımla', exact: true }).click();
  await admin.getByRole('dialog').getByRole('button', { name: 'Yayımla', exact: true }).click();
  await admin.getByText('Sürüm 1 yayımlandı ve kullanıma açıldı.', { exact: true }).waitFor();

  const owner = await login('Can Arslan');
  await owner.goto(base + '/dilekceler/yeni');
  await owner.getByText('Tarayıcı kişisel imza', { exact: true }).click();
  await owner.getByLabel('Dilekçe başlığı').fill('Bireysel yazışma denemesi');
  await owner.getByRole('textbox', { name: /^Konu/ }).fill('Bir kişiye yazışma');
  await owner.getByRole('textbox', { name: /^Açıklama/ }).fill('Kişinin kendi adına imzalamasını istiyorum.');
  await owner.getByRole('combobox', { name: /İmzalayacak kişi/ }).click();
  await owner.getByRole('option', { name: /Ali Çelik/ }).click();
  await owner.locator('.docx-preview-host').getByText('Kişinin kendi adına imzalamasını istiyorum.', { exact: true }).waitFor();
  await owner.locator('.docx-preview-host section.docx').first().waitFor();
  const hostBox = await owner.locator('.docx-preview-host').boundingBox();
  const pageBox = await owner.locator('.docx-preview-host section.docx').first().boundingBox();
  assert.ok(pageBox.x >= hostBox.x && pageBox.x + pageBox.width <= hostBox.x + hostBox.width + 2, 'Belge önizlemesinin iki kenarı da görünmeli.');
  await owner.screenshot({ path: out + 'personal-petition.png', fullPage: true });
  await owner.getByRole('button', { name: 'Onaya gönder', exact: true }).click();
  await owner.getByRole('dialog').getByRole('button', { name: 'Gönder', exact: true }).click();
  await owner.waitForURL((url) => url.pathname.startsWith('/dilekceler/') && url.pathname !== '/dilekceler/yeni');
  const petitionPath = new URL(owner.url()).pathname;
  const signer = await login('Ali Çelik');
  await signer.goto(base + '/onaylar');
  await signer.getByRole('link', { name: /Bireysel yazışma denemesi/ }).click();
  await signer.getByLabel('Belgenin içeriğini okudum; kararımı kendi adıma veriyorum.').check();
  await signer.getByRole('button', { name: 'Onayla', exact: true }).click();
  await signer.getByText('Onayınız kaydedildi.', { exact: true }).waitFor();
  assert.equal((await getDoc(doc(db, 'petitions', petitionPath.split('/').at(-1)))).data().status, 'approved');
  await signer.screenshot({ path: out + 'personal-signed.png', fullPage: true });
  await signer.setViewportSize({ width: 390, height: 844 });
  await signer.goto(base);
  await signer.getByRole('button', { name: 'İşlem bul', exact: true }).first().click();
  await signer.getByRole('textbox', { name: 'İşlem ara' }).fill('oda');
  await signer.screenshot({ path: out + 'search-mobile.png', fullPage: true });
  assert.equal(await signer.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await signer.getByRole('dialog').getByRole('link', { name: 'Oda rezervasyonu' }).click();
  await signer.waitForURL('**/oda-rezervasyonu');
  await signer.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.deepEqual(errors, []);
  console.log('Sadeleştirme: menü, Ctrl+K arama, aynı adlı roller, komite başvuru bağlantısı, şablon oluşturma, rolü olmayan kişiye imza ve mobil görünüm geçti.');
} catch (error) {
  await lastPage?.screenshot({ path: out + 'failure.png', fullPage: true }).catch(() => {});
  if (errors.length) console.error(errors);
  throw error;
} finally {
  await browser?.close();
  await server.close();
  if (memberRef && memberBefore) await setDoc(memberRef, memberBefore);
  await deleteDoc(doc(db, 'roles', 'smoke-duplicate'));
  await signOut(auth);
  await terminate(db);
  await deleteApp(app);
}
